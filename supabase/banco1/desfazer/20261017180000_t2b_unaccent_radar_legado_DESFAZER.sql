-- DESFAZER de 20261017180000_t2b_unaccent_radar_legado.sql (17/10/2026).
-- Recria as 7 tabelas legadas VAZIAS (estrutura, indices, RLS, politica e permissoes de antes),
-- as 3 views, a amarracao de votos_parlamentares, a leitura publica da radar_gastos e o unaccent
-- no schema public. Os dados nao voltam: as tabelas tinham 0 linhas.

begin;

alter extension unaccent set schema public;
grant select on public.radar_gastos to anon, authenticated;

create table public.legislativo_projetos (
  id uuid primary key default gen_random_uuid(),
  titulo_projeto text not null,
  link_oficial text not null unique,
  resumo_ia text,
  biblio_transparente jsonb,
  regua_imparcialidade double precision,
  data_atualizacao timestamptz default now(),
  autor_principal_id uuid references public.agentes_politicos(id)
);
alter table public.votos_parlamentares
  add constraint votos_parlamentares_projeto_id_fkey foreign key (projeto_id) references public.legislativo_projetos(id);

create table public.registros_votos (
  id uuid primary key default gen_random_uuid(),
  agente_id uuid references public.agentes_politicos(id),
  projeto_id uuid references public.legislativo_projetos(id),
  posicao_voto text,
  data_votacao date,
  ementa_resumida text,
  alerta_incoerencia boolean default false
);
create index idx_votos_agente on public.registros_votos using btree (agente_id);

create table public.executivo_licitacoes (
  id bigint primary key,
  data_auditoria timestamptz default current_timestamp,
  orgao_nome text,
  unidade_gestora text,
  objeto_original text,
  modalidade text,
  valor_estimado numeric(15,2),
  resumo_cidadao text,
  fidelidade_nota integer,
  alerta_auditoria text,
  link_fonte text,
  agente_responsavel_id uuid references public.agentes_politicos(id),
  categoria_gasto text,
  agente_autorizador_id uuid references public.agentes_politicos(id)
);

create table public.gastos_cotas_individuais (
  id uuid primary key default gen_random_uuid(),
  agente_id uuid references public.agentes_politicos(id),
  ano_mes date,
  categoria_gasto text,
  descricao_detalhada text,
  valor_total numeric(15,2),
  fornecedor_nome text,
  link_comprovante text,
  created_at timestamptz default now()
);
create index idx_gastos_agente on public.gastos_cotas_individuais using btree (agente_id);

create table public.analises_politicas (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  titulo text,
  resumo_gemini text,
  auditoria_llama text,
  link_oficial text
);

create table public.pid2026_judiciario (
  id serial primary key,
  data_processamento timestamp default current_timestamp,
  data_licitacao date,
  tribunal varchar(255),
  objeto_original text,
  resumo_ludico text,
  nota_transparencia integer,
  justificativa_auditoria text,
  modalidade varchar(100),
  link_original text
);

create table public.processos_judiciarios (
  id serial primary key,
  numero_processo varchar(50) not null unique,
  tribunal varchar(20) not null,
  orgao_julgador varchar(255),
  classe_processual varchar(255),
  resumo_leigo text,
  analise_tecnica text,
  assuntos_lista text,
  nota_integridade numeric(3,1),
  justificativa_auditoria text,
  conflito_identificado boolean default false,
  data_movimentacao_oficial date,
  link_fonte_oficial text,
  criado_em timestamp default current_timestamp,
  atualizado_em timestamp default current_timestamp,
  agente_id uuid references public.agentes_politicos(id),
  politico_envolvido_id uuid references public.agentes_politicos(id)
);
create index idx_numero_processo on public.processos_judiciarios using btree (numero_processo);

-- RLS, politica de leitura publica e permissoes, iguais as de antes, nas 7 tabelas.
do $$
declare t text;
begin
  foreach t in array array['legislativo_projetos','registros_votos','executivo_licitacoes',
                           'gastos_cotas_individuais','analises_politicas','pid2026_judiciario',
                           'processos_judiciarios'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('create policy "Leitura publica" on public.%I for select to anon, authenticated using (true)', t);
    execute format('grant select on public.%I to anon, authenticated', t);
    execute format('grant all on public.%I to service_role', t);
  end loop;
end $$;

create view public.vista_comparativa_gastos with (security_invoker = true) as
 select categoria_gasto, avg(valor_estimado) as media_categoria, max(valor_estimado) as maior_gasto
   from public.executivo_licitacoes group by categoria_gasto;

create view public.ranking_gastos_politicos with (security_invoker = true) as
 select ap.nome_urna, ap.partido_atual, gci.categoria_gasto,
        sum(gci.valor_total) as total_gasto, count(gci.id) as quantidade_lancamentos
   from public.agentes_politicos ap join public.gastos_cotas_individuais gci on ap.id = gci.agente_id
  group by ap.nome_urna, ap.partido_atual, gci.categoria_gasto
  order by sum(gci.valor_total) desc;

create view public.resumo_coerencia_votos with (security_invoker = true) as
 select ap.nome_urna, count(rv.id) as total_votos,
        sum(case when rv.alerta_incoerencia then 1 else 0 end) as votos_incoerentes
   from public.agentes_politicos ap join public.registros_votos rv on ap.id = rv.agente_id
  group by ap.nome_urna;

grant select on public.vista_comparativa_gastos, public.ranking_gastos_politicos, public.resumo_coerencia_votos to anon, authenticated;
grant all on public.vista_comparativa_gastos, public.ranking_gastos_politicos, public.resumo_coerencia_votos to service_role;

commit;
